"""病句校对 prompt 构建。

设计要点：
- 只让模型做"语境类"问题（病句/搭配/成语误用/的地得），错别字和标点由本地规则库负责，不重复。
- 强制模型只输出 JSON 数组，便于后端解析，不要解释性文字。
- 每条给出原片段、建议、简短理由，供前端展示并标「AI 判定」。
"""

SYSTEM = (
    "你是中文文字校对助手，依据现代汉语规范，专门检测需要理解上下文的问题："
    "语序不当、搭配不当、成分残缺或赘余、关联词误用、成语误用、的/地/得误用、语义重复。"
    "不要检测单纯的错别字和标点（这些由其他模块负责）。"
)

# 要求严格 JSON 输出，字段与前端 issue 对齐
INSTRUCTION = (
    "请校对下面的文本，只返回一个 JSON 数组，不要有任何额外说明文字。"
    "数组每个元素形如："
    '{"wrong":"原文中有问题的片段","right":"修改建议","note":"简短理由(20字内)"}。'
    "若没有发现问题，返回空数组 []。"
    "只针对确有把握的问题，宁缺毋滥。文本如下：\n\n"
)


def build_messages(text: str):
    """返回 chat 所需的 system / user 消息。"""
    return SYSTEM, INSTRUCTION + text
